-- 1. GUARDA: Aborta si la base tiene el modelo antiguo con tabla 'cliente'
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'cliente'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'estudiantes'
    ) THEN
        RAISE EXCEPTION 'Esta base tiene el modelo antiguo (tabla cliente); use una base nueva';
    END IF;
END $$;

-- 2. SI EXISTE vista_solicitudes QUE DEPENDE DE LA TABLA solicitudes, SE ELIMINA TEMPORALMENTE
DROP VIEW IF EXISTS vista_solicitudes;

-- 3. RENOMBRADO DE solicitudes_prestamo A solicitudes SI ES NECESARIO
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'solicitudes_prestamo'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'solicitudes'
    ) THEN
        ALTER TABLE solicitudes_prestamo RENAME TO solicitudes;
    END IF;
END $$;

-- 4. CREACIÓN DE LAS 4 TABLAS BASE SI NO EXISTEN
CREATE TABLE IF NOT EXISTS estudiantes (
    id_estudiante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(15) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    edad INTEGER NOT NULL,
    telefono VARCHAR(20),
    correo VARCHAR(120),
    promedio_notas NUMERIC(4, 2) NOT NULL DEFAULT 14.00,
    porcentaje_asistencia NUMERIC(5, 2) NOT NULL DEFAULT 100.00,
    estado_universidad VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    ciclo_actual INTEGER NOT NULL DEFAULT 1,
    fecha_registro DATE DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS prestamos (
    id_prestamo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante BIGINT NOT NULL,
    monto NUMERIC(12, 2) NOT NULL,
    cuotas INTEGER NOT NULL,
    tasa_interes NUMERIC(5, 2) NOT NULL DEFAULT 10.00,
    saldo NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Activo',
    fecha_inicio DATE DEFAULT CURRENT_DATE,
    dias_mora INTEGER NOT NULL DEFAULT 0,
    interes_mora NUMERIC(12, 2) NOT NULL DEFAULT 0.00
);

CREATE TABLE IF NOT EXISTS pagos (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo BIGINT NOT NULL,
    monto NUMERIC(12, 2) NOT NULL,
    cuota_numero INTEGER NOT NULL,
    metodo_pago VARCHAR(50) NOT NULL,
    fecha_pago DATE DEFAULT CURRENT_DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO',
    id_cuota BIGINT
);

CREATE TABLE IF NOT EXISTS solicitudes (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante BIGINT NOT NULL,
    monto_solicitado NUMERIC(12, 2) NOT NULL,
    cuotas_solicitadas INTEGER NOT NULL,
    estado_solicitud VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    recomendacion_sistema VARCHAR(200),
    observacion VARCHAR(255),
    atendido_por VARCHAR(50),
    fecha_solicitud DATE DEFAULT CURRENT_DATE
);

-- 5. CORRECCIONES Y AJUSTES DE COLUMNAS EN LAS 4 TABLAS BASE
DO $$
BEGIN
    -- solicitudes.observacion
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'solicitudes' AND column_name = 'observacion'
    ) THEN
        ALTER TABLE solicitudes ADD COLUMN observacion VARCHAR(255);
    END IF;

    -- solicitudes.atendido_por
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'solicitudes' AND column_name = 'atendido_por'
    ) THEN
        ALTER TABLE solicitudes ADD COLUMN atendido_por VARCHAR(50);
    END IF;

    -- solicitudes.recomendacion_sistema ampliar a varchar(200)
    ALTER TABLE solicitudes ALTER COLUMN recomendacion_sistema TYPE VARCHAR(200);

    -- pagos.estado
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'pagos' AND column_name = 'estado'
    ) THEN
        ALTER TABLE pagos ADD COLUMN estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO';
    END IF;

    -- pagos.id_cuota
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'pagos' AND column_name = 'id_cuota'
    ) THEN
        ALTER TABLE pagos ADD COLUMN id_cuota BIGINT;
    END IF;

    -- Conversión a DATE de fecha_registro (estudiantes), fecha_pago (pagos) y fecha_solicitud (solicitudes)
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'estudiantes' 
          AND column_name = 'fecha_registro' AND data_type <> 'date'
    ) THEN
        ALTER TABLE estudiantes ALTER COLUMN fecha_registro TYPE DATE USING fecha_registro::date;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'pagos' 
          AND column_name = 'fecha_pago' AND data_type <> 'date'
    ) THEN
        ALTER TABLE pagos ALTER COLUMN fecha_pago TYPE DATE USING fecha_pago::date;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' AND table_name = 'solicitudes' 
          AND column_name = 'fecha_solicitud' AND data_type <> 'date'
    ) THEN
        ALTER TABLE solicitudes ALTER COLUMN fecha_solicitud TYPE DATE USING fecha_solicitud::date;
    END IF;
END $$;

-- 6. RECREACIÓN IDEMPOTENTE DE CLAVES FORÁNEAS DE LAS TABLAS BASE A ON DELETE RESTRICT
DO $$
DECLARE
    r RECORD;
BEGIN
    -- fk_prestamos_estudiante
    FOR r IN (
        SELECT constraint_name FROM information_schema.table_constraints 
        WHERE table_schema = 'public' AND table_name = 'prestamos' AND constraint_type = 'FOREIGN KEY'
          AND constraint_name = 'fk_prestamos_estudiante'
    ) LOOP
        EXECUTE 'ALTER TABLE prestamos DROP CONSTRAINT ' || quote_ident(r.constraint_name);
    END LOOP;
    ALTER TABLE prestamos ADD CONSTRAINT fk_prestamos_estudiante 
        FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante) ON DELETE RESTRICT;

    -- fk_pagos_prestamo
    FOR r IN (
        SELECT constraint_name FROM information_schema.table_constraints 
        WHERE table_schema = 'public' AND table_name = 'pagos' AND constraint_type = 'FOREIGN KEY'
          AND constraint_name = 'fk_pagos_prestamo'
    ) LOOP
        EXECUTE 'ALTER TABLE pagos DROP CONSTRAINT ' || quote_ident(r.constraint_name);
    END LOOP;
    ALTER TABLE pagos ADD CONSTRAINT fk_pagos_prestamo 
        FOREIGN KEY (id_prestamo) REFERENCES prestamos(id_prestamo) ON DELETE RESTRICT;

    -- fk_solicitudes_estudiante
    FOR r IN (
        SELECT constraint_name FROM information_schema.table_constraints 
        WHERE table_schema = 'public' AND table_name = 'solicitudes' AND constraint_type = 'FOREIGN KEY'
          AND constraint_name = 'fk_solicitudes_estudiante'
    ) LOOP
        EXECUTE 'ALTER TABLE solicitudes DROP CONSTRAINT ' || quote_ident(r.constraint_name);
    END LOOP;
    ALTER TABLE solicitudes ADD CONSTRAINT fk_solicitudes_estudiante 
        FOREIGN KEY (id_estudiante) REFERENCES estudiantes(id_estudiante) ON DELETE RESTRICT;
END $$;

