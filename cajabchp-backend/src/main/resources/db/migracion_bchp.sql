-- 12. CRONOGRAMA RETROACTIVO PARA PRÉSTAMOS EXISTENTES SIN CUOTAS
DO $$
DECLARE
    r_prestamo RECORD;
    v_total NUMERIC(12, 2);
    v_cuota_monto NUMERIC(12, 2);
    v_acumulado NUMERIC(12, 2);
    v_cuota_final NUMERIC(12, 2);
    v_vencimiento DATE;
    v_estado_cuota VARCHAR(20);
    k INT;
BEGIN
    FOR r_prestamo IN 
        SELECT id_prestamo, monto, cuotas, tasa_interes, fecha_inicio, estado
        FROM prestamos p
        WHERE NOT EXISTS (SELECT 1 FROM cuotas c WHERE c.id_prestamo = p.id_prestamo)
          AND cuotas > 0
    LOOP
        v_total := ROUND(r_prestamo.monto * (1.0 + (r_prestamo.tasa_interes / 100.0)), 2);
        v_cuota_monto := ROUND(v_total / r_prestamo.cuotas, 2);
        v_acumulado := 0.00;

        FOR k IN 1..r_prestamo.cuotas LOOP
            v_vencimiento := (COALESCE(r_prestamo.fecha_inicio, CURRENT_DATE) + (k || ' month')::INTERVAL)::DATE;
            
            IF k = r_prestamo.cuotas THEN
                v_cuota_final := v_total - v_acumulado;
            ELSE
                v_cuota_final := v_cuota_monto;
                v_acumulado := v_acumulado + v_cuota_final;
            END IF;

            IF r_prestamo.estado = 'Pagado' THEN
                v_estado_cuota := 'Pagada';
            ELSE
                v_estado_cuota := 'Pendiente';
            END IF;

            INSERT INTO cuotas (id_prestamo, numero_cuota, fecha_vencimiento, monto, estado)
            VALUES (r_prestamo.id_prestamo, k, v_vencimiento, v_cuota_final, v_estado_cuota)
            ON CONFLICT (id_prestamo, numero_cuota) DO NOTHING;
        END LOOP;
    END LOOP;

    -- Vincular pagos existentes a su respectiva cuota (id_prestamo, cuota_numero)
    UPDATE pagos
    SET id_cuota = c.id_cuota
    FROM cuotas c
    WHERE pagos.id_prestamo = c.id_prestamo 
      AND pagos.cuota_numero = c.numero_cuota
      AND pagos.id_cuota IS NULL;

    -- Marcar "Pagada" la cuota si la suma de pagos no anulados cubre el monto (tolerancia 0.01)
    UPDATE cuotas
    SET estado = 'Pagada'
    WHERE cuotas.estado <> 'Pagada'
      AND (
          SELECT COALESCE(SUM(pg.monto), 0) 
          FROM pagos pg 
          WHERE pg.id_cuota = cuotas.id_cuota 
            AND COALESCE(pg.estado, 'REGISTRADO') <> 'ANULADO'
      ) >= (cuotas.monto - 0.01);

END $$;

-- 13. RECREAR VISTA vista_solicitudes SI APLICA
CREATE OR REPLACE VIEW vista_solicitudes AS
SELECT 
    s.id_solicitud,
    (e.nombre || ' ' || e.apellido) AS estudiante,
    e.dni,
    e.promedio_notas,
    e.porcentaje_asistencia,
    e.estado_universidad,
    s.monto_solicitado,
    s.cuotas_solicitadas,
    s.estado_solicitud,
    s.recomendacion_sistema,
    s.atendido_por,
    s.fecha_solicitud
FROM solicitudes s
JOIN estudiantes e ON s.id_estudiante = e.id_estudiante;
