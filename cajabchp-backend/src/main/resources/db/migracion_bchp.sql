-- 10. TRIGGERS DE AUDITORÍA Y SEGURIDAD FINANCIERA
CREATE OR REPLACE FUNCTION fn_auditar()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO auditoria_financiera (tabla, operacion, usuario, fecha_hora, valor_anterior)
    VALUES (
        TG_TABLE_NAME,
        TG_OP,
        COALESCE(NULLIF(current_setting('bchp.usuario', true), ''), current_user),
        NOW(),
        to_jsonb(OLD)
    );
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_prestamos ON prestamos;
